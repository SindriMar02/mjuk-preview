/* Writes the list the shop-fields plugin shows in its dropdowns: her groups, her nine materials in
   her ranking, and her designs (families), all from tools/groups.json, so the WooCommerce product
   screen and the shop's filters can never disagree about what exists.

     node tools/shop-fields-json.mjs          writes 04-platform/mjuk-woo-sandbox/mu-plugins/sndr-shop-fields.json
     node tools/shop-fields-json.mjs --check  exits 1 when that file no longer matches groups.json

   Designs she adds herself in WordPress (Products → Shop designs) are kept by the plugin and read
   back by tools/pull-woo.mjs; they never need this file. */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { G, MATERIALS } from './groups.mjs';

const OUT = path.resolve(import.meta.dirname, '../../../04-platform/mjuk-woo-sandbox/mu-plugins/sndr-shop-fields.json');
export const body = {
  groups: G.groups.map(({ key, name, is }) => ({ key, name, is })),
  materials: MATERIALS.map(({ key, name, is }) => ({ key, name, is })),
  // "said": a double-faced design names both sides in words and belongs to no single material
  designs: G.families.map(f => ({ key: f.key, name: f.name, is: f.is, group: f.group, material: f.material || '', ...(f.said ? { two: true } : {}) })),
};
const json = obj => JSON.stringify(obj, null, 1) + '\n';
// the version the plugin reports in /lists; tools/pull-woo.mjs compares it with this sheet
export const version = crypto.createHash('sha256').update(JSON.stringify(body)).digest('hex').slice(0, 12);
const main = import.meta.url === pathToFileURL(process.argv[1] || '').href;
const out = json({ _about: 'Generated by 03-prototypes/mjuk-experimental/tools/shop-fields-json.mjs from tools/groups.json. Do not edit by hand.', version, ...body });

if (main && process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== out) { console.error(`${path.relative(process.cwd(), OUT)} is out of date with tools/groups.json: run node tools/shop-fields-json.mjs`); process.exit(1); }
  console.log(`shop-fields list up to date (${version})`); process.exit(0);
}
if (main && !process.argv.includes('--check')) {
fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT} (${body.groups.length} groups, ${body.materials.length} materials, ${body.designs.length} designs, version ${version})`);
}
